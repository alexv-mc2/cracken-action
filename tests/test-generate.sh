#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
server=
cleanup() {
  if [[ -n "$server" ]]; then kill "$server" 2>/dev/null || true; wait "$server" 2>/dev/null || true; fi
  python3 -c 'import shutil,sys; shutil.rmtree(sys.argv[1])' "$tmp"
}
trap cleanup EXIT
mkdir -p "$tmp/bin" "$tmp/scripts" "$tmp/source with spaces/.git" "$tmp/tmp"
export TMPDIR="$tmp/tmp"
cp scripts/*.sh "$tmp/scripts/"
python3 tests/generate_api.py "$tmp/port" "$tmp/records" &
server=$!
for ((i=0; i<100; i++)); do [[ -s "$tmp/port" ]] && break; sleep 0.05; done
CRACKEN_API_URL="http://127.0.0.1:$(cat "$tmp/port")/functions/v1/api-v1"
export CRACKEN_API_URL
CRACKEN_API_KEY="crk_aaaaaaaaaaaa_$(printf '%043d' 0)"
export CRACKEN_API_KEY
export CRACKEN_PROJECT_ID=11111111-1111-4111-8111-111111111111 VERSION=1.0 WAIT=false TIMEOUT=10
export GITHUB_OUTPUT="$tmp/output" CRACKEN_SBOM_PATH_FILE="$tmp/sbom-path" FAKE_SYFT_ARGS="$tmp/args"
export GITHUB_REPOSITORY=customer/repository GITHUB_SHA=abcdef1234567890
export CRACKEN_GENERATE=syft SYFT_VERSION=1.55.0 SCAN_PATH="$tmp/source with spaces"
export CRACKEN_SYFT_TEST_MODE=1 SYFT_DOWNLOAD_BASE="file://$tmp/releases"
export PATH="$tmp/bin:$PATH"
unset SBOM_FILE SYFT_INSECURE_SKIP_PIN
cat > "$tmp/good-syft" <<'FAKE'
#!/bin/sh
set -eu
if [ "$1" = version ]; then printf '%s\n' '{"version":"1.55.0"}'; exit; fi
[ "$1" = scan ] || exit 1
printf '%s\n' "$@" > "$FAKE_SYFT_ARGS"
for arg do
  case "$arg" in cyclonedx-json=*) output=${arg#cyclonedx-json=} ;; esac
done
printf '%s' '{"bomFormat":"CycloneDX","components":[{"name":"fixture","licenses":[{"license":{"id":"MIT"}}]}],"secret-content":"do-not-log"}' > "$output"
FAKE
chmod +x "$tmp/good-syft"
cp "$tmp/good-syft" "$tmp/bin/syft"
checks=0
run() {
  local label=$1 expected=$2 actual=0
  : > "$GITHUB_OUTPUT"; : > "$tmp/log"
  python3 -c 'from pathlib import Path; import sys; [Path(p).unlink(missing_ok=True) for p in sys.argv[1:]]' "$FAKE_SYFT_ARGS" "$CRACKEN_SBOM_PATH_FILE"
  sh "$tmp/scripts/generate-syft.sh" > "$tmp/log" 2>&1 || actual=$?
  if [[ "$actual" != "$expected" ]]; then cat "$tmp/log"; echo "FAIL $label: expected $expected, got $actual"; exit 1; fi
  if grep -Fq "$CRACKEN_API_KEY" "$tmp/log" "$GITHUB_OUTPUT" || grep -q do-not-log "$tmp/log"; then echo 'FAIL secret disclosure'; exit 1; fi
  checks=$((checks+1)); echo "ok $checks - $label (exit $actual)"
}
run 'exact PATH version generates and uploads' 0
sbom=$(sed -n 's/^sbom-path=//p' "$GITHUB_OUTPUT")
[[ -r "$sbom" && "$sbom" = /* && "$(cat "$CRACKEN_SBOM_PATH_FILE")" = "$sbom" ]]
grep -Fxq "dir:$SCAN_PATH" "$FAKE_SYFT_ARGS"
grep -Fxq './.git' "$FAKE_SYFT_ARGS"
# Check option/value pairs so unrelated arguments cannot satisfy the exclusions.
python3 - "$FAKE_SYFT_ARGS" <<'PYTEST'
from pathlib import Path
import sys
args = Path(sys.argv[1]).read_text().splitlines()
exclusions = [args[i + 1] for i, arg in enumerate(args[:-1]) if arg == "--exclude"]
assert "./.github" in exclusions, "CI tooling directory must be excluded"
selection = args[args.index("--select-catalogers") + 1].split(",")
assert "-github-actions-usage-cataloger" in selection
assert "-github-action-workflow-usage-cataloger" in selection
PYTEST
grep -Fxq -- '--source-name' "$FAKE_SYFT_ARGS"
grep -Fxq "$GITHUB_REPOSITORY" "$FAKE_SYFT_ARGS"
grep -Fxq "$GITHUB_SHA" "$FAKE_SYFT_ARGS"
run 'identical generated bytes reuse upload idempotency key' 0
python3 - "$tmp/records" "$sbom" <<'PY'
import hashlib, json, sys
records = [json.loads(line) for line in open(sys.argv[1])]
assert len(records) == 2 and records[0]["key"] == records[1]["key"]
assert records[0]["digest"] == hashlib.sha256(open(sys.argv[2], "rb").read()).hexdigest()
assert records[0]["body"]["components"][0]["licenses"][0]["license"]["id"] == "MIT"
PY
VERSION=2.0 run 'new release changes idempotency key' 0
python3 - "$tmp/records" <<'PY'
import json, sys
records = [json.loads(line) for line in open(sys.argv[1])]
assert records[0]["key"] != records[2]["key"]
PY
SBOM_FILE="$sbom" run 'explicit SBOM and generation conflict' 1
SYFT_VERSION=1.54.1 run 'unpinned version rejected even on PATH' 1
CRACKEN_GENERATE=invalid run 'invalid generator rejected' 1
# Compare the none path byte-for-byte with the existing upload script outputs/logs.
SBOM_FILE="$sbom" CRACKEN_GENERATE=none run 'none uploads an existing SBOM unchanged' 0
cp "$GITHUB_OUTPUT" "$tmp/none-output"; cp "$tmp/log" "$tmp/none-log"
: > "$GITHUB_OUTPUT"
SBOM_FILE="$sbom" sh scripts/upload.sh > "$tmp/direct-log" 2>&1
cmp "$GITHUB_OUTPUT" "$tmp/none-output"; cmp "$tmp/direct-log" "$tmp/none-log"
[[ ! -e "$CRACKEN_SBOM_PATH_FILE" ]]
GITHUB_REPOSITORY='' GITHUB_SHA='' CI_PROJECT_PATH=group/project CI_COMMIT_SHA=gitlabsha run 'GitLab metadata' 0
grep -Fxq group/project "$FAKE_SYFT_ARGS"; grep -Fxq gitlabsha "$FAKE_SYFT_ARGS"
# Wrong PATH version must never be used to scan; downloads are file:// only.
cat > "$tmp/bin/syft" <<'FAKE'
#!/bin/sh
if [ "$1" = version ]; then printf '%s\n' '{"version":"0.0.1"}'; exit; fi
printf '%s\n' 'wrong PATH binary used to scan' >&2
exit 99
FAKE
chmod +x "$tmp/bin/syft"
make_release() {
  local version=$1 release="$tmp/releases/v$1"
  mkdir -p "$release" "$tmp/archive"
  sed "s/1.55.0/$version/g" "$tmp/good-syft" > "$tmp/archive/syft"
  chmod +x "$tmp/archive/syft"
  for os in linux darwin; do
    for arch in amd64 arm64; do
      tar -czf "$release/syft_${version}_${os}_${arch}.tar.gz" -C "$tmp/archive" syft
    done
  done
  python3 - "$release" "$version" <<'PY'
from pathlib import Path
import hashlib, sys
release = Path(sys.argv[1])
with (release / f"syft_{sys.argv[2]}_checksums.txt").open("w") as checksums:
    for archive in sorted(release.glob("*.tar.gz")):
        checksums.write(f"{hashlib.sha256(archive.read_bytes()).hexdigest()}  {archive.name}\n")
PY
}
make_release 1.55.0
release="$tmp/releases/v1.55.0"
# Only a fixture copy gets a replacement pin; production has no env pin override.
python3 - "$tmp/scripts/generate-syft.sh" "$release/syft_1.55.0_checksums.txt" <<'PY'
from pathlib import Path
import hashlib, sys
script = Path(sys.argv[1])
source = script.read_text()
pin = "aba5ac8ee870bb93fd3b2058471ffe7e57492ba673b5e0bcbfca92006c2f4dc7"
assert pin in source
script.write_text(source.replace(pin, hashlib.sha256(Path(sys.argv[2]).read_bytes()).hexdigest()))
PY
run 'wrong PATH version downloads and verifies pinned release' 0
# All supported host tuples select the expected official release asset name.
cat > "$tmp/bin/uname" <<'FAKE'
#!/bin/sh
case "$1" in -s) printf '%s\n' "$FAKE_OS" ;; -m) printf '%s\n' "$FAKE_ARCH" ;; *) exit 1 ;; esac
FAKE
chmod +x "$tmp/bin/uname"
for host in Linux:x86_64 Linux:aarch64 Darwin:x86_64 Darwin:arm64; do
  FAKE_OS=${host%:*} FAKE_ARCH=${host#*:} run "supported platform $host" 0
done
FAKE_OS=FreeBSD FAKE_ARCH=x86_64 run 'unsupported operating system rejected' 1
FAKE_OS=Linux FAKE_ARCH=riscv64 run 'unsupported architecture rejected' 1
python3 -c 'from pathlib import Path; import sys; Path(sys.argv[1]).unlink()' "$tmp/bin/uname"
cp "$release/syft_1.55.0_checksums.txt" "$tmp/checksums"
printf '\n' >> "$release/syft_1.55.0_checksums.txt"
run 'swapped checksums file fails pinned digest' 1
[[ ! -e "$FAKE_SYFT_ARGS" ]]
SYFT_INSECURE_SKIP_PIN=true run 'default pin cannot be bypassed by custom-version opt-out' 1
[[ ! -e "$FAKE_SYFT_ARGS" ]]
cp "$tmp/checksums" "$release/syft_1.55.0_checksums.txt"
for archive in "$release"/*.tar.gz; do printf corruption >> "$archive"; done
run 'archive checksum mismatch fails before execution' 1
[[ ! -e "$FAKE_SYFT_ARGS" ]]
# Opt-out permits custom versions but does not bypass archive checksum verification.
make_release 1.54.1
SYFT_VERSION=1.54.1 SYFT_INSECURE_SKIP_PIN=true run 'explicit custom-version pin opt-out' 0
for archive in "$tmp/releases/v1.54.1"/*.tar.gz; do printf corruption >> "$archive"; done
SYFT_VERSION=1.54.1 SYFT_INSECURE_SKIP_PIN=true run 'custom-version opt-out still verifies archive checksum' 1
[[ ! -e "$FAKE_SYFT_ARGS" ]]
SYFT_VERSION=1.54.1 SYFT_INSECURE_SKIP_PIN=maybe run 'invalid pin opt-out rejected' 1
CRACKEN_SYFT_TEST_MODE=0 run 'download mirror blocked outside tests' 1
printf 'PASS: %s generation scenarios\n' "$checks"
